namespace skgpu::graphite {

class DrawContext;
class Recorder;

// Holds the cpu-side copy of alpha values generated by sparse strips rasterization, and handles
// their allocation and upload into textures.
//
// Regular pages: the manager uses a two page system; when the first page is exhausted, the second
// page is created with double the allocation. Uploads occur when the drawContext flushes; if two
// pages are active at flush time, the older page is retired, and the larger page takes its place as
// the initial page. Regular pages are append-only and are never overwritten.
//
// Overflow page: if both regular pages are exhausted between flushes, the remaining alphas of a
// draw are staged on the CPU and, once the draw's flush decision has been made, committed to a
// third "overflow" page (see commitOverflow()). A sampled texture can't be modified between the
// draws of a render pass, and a DrawContext's uploads all execute before its render pass, so the
// overflow page is append-only within a flush epoch. It is overwritten in place once every draw
// that sampled it has been flushed. If it is still in use but too small, it is replaced by a larger
// page instead (up to a soft cap, past which the draw flushes first).
class AlphaAtlasManager {
public:
    static constexpr uint16_t kOverflowSlot = SparseStripConfig::kOverflowSlot;
    static constexpr uint32_t kInvalidPageID = 0;

    explicit AlphaAtlasManager(Recorder* recorder);

    // ---- Strip generation ----

    // TODO(thomsmit): bitpack the texture page into the alpha index?
    // Returns a pointer to memory for writing `numBytes` alphas of the current run. Overallocates
    // the active page's buffer if the write exceeds fCapacityBytes. Once both regular pages are
    // full, the memory is in the overflow staging buffer instead.
    uint8_t* requestAlphaSpace(int32_t numBytes);

    // Finalizes the current boundary run.
    // If the run straddled pages, allocates the next page and copies the overrun data, or moves the
    // run into the overflow staging buffer if both regular pages are full. Returns a pair of
    // {alphaIndex, texPage} on success, which indicate the page-local byte offset and binding slot,
    // respectively. For kOverflowSlot, alphaIndex is an offset into the staging buffer until
    // commitOverflow() rebases it into the overflow page.
    std::optional<std::pair<int32_t, uint16_t>> finalizeRun();

    // ---- Per-draw lifecycle ----

    // Called before generating strips for a new draw. Discards partial state (an unfinished run or
    // uncommitted overflow alphas) left behind by a previous draw that failed or was never
    // committed.
    void beginDraw();

    // Binds the regular pages to `ends`; bindings without a page receive a placeholder. Must be
    // called once strip generation completes. The regular page bindings must not change afterwards:
    // a flush before the draw is recorded may retire a page, but `ends` keeps it alive.
    void bindPages(EndCaps* ends) const;

    // Returns true if the staged overflow alphas can only be committed by replacing the overflow
    // page in a way that would exceed kOverflowSoftCapBytes, while a full flush would allow the
    // current overflow page to be overwritten in place instead.
    bool overflowCommitNeedsFlush() const;

    // Copies the alphas staged for `ends` into the overflow page, rebases its overflow caps, and
    // binds the overflow page. A no-op if `ends` has no pending overflow. Must be called before any
    // other draw generates strips. Returns false if an overflow page couldn't be allocated.
    bool commitOverflow(EndCaps* ends);

    // Marks a sparse strips draw as in flight, from strip generation until it has been recorded to
    // a DrawContext. Flush tokens only account for recorded draws, but between commitOverflow() and
    // recording, shading.toKey() may record nested draws and even trigger a full flush. So while
    // another draw is in flight, the overflow page is never overwritten in place. When the scope
    // closes, every page bound in `ends` is marked as used by the current flush.
    class DrawScope {
    public:
        DrawScope(AlphaAtlasManager* manager, const EndCaps* ends);
        ~DrawScope();

        DrawScope(const DrawScope&) = delete;
        DrawScope& operator=(const DrawScope&) = delete;

    private:
        AlphaAtlasManager* fManager;
        const EndCaps* fEnds;
    };

    // ---- Flush lifecycle ----

    void recordUploads(DrawContext* dc);
    void freeGpuResources();

    // Alphas recorded so far are no longer considered resident (e.g. after a Recording failed, or
    // when Recordings may execute out of order). The pages themselves remain usable for new alphas.
    void evictAtlases();

    // ---- Reuse tracking ----
    //
    // Every page receives a unique ID when created, and a new ID whenever its contents are
    // invalidated. Alphas written to a regular page stay present at their offset for as long as
    // findResidentSlot() returns a slot for that page's ID. The overflow page is overwritten in
    // place, so its contents are never resident.
    uint32_t pageID(uint16_t slot) const;
    std::optional<uint16_t> findResidentSlot(uint32_t pageID) const;
    // The nextFlushToken() when a draw binding the page was last committed or recorded.
    skgpu::Token lastUseToken(uint16_t slot) const;

    // ---- Strip reuse ----
    //
    // Strips generated for a shape are cached along with the IDs of the regular pages holding their
    // alphas, so that a later draw of the shape with the same transform, up to an integer
    // translation, can reuse them while those pages are resident. Strips that depend on the clip
    // are only reused by draws with the same transform and clip. Strips with overflow caps are
    // never cached.

    // If strips cached for `key` only reference resident alphas, writes them to `ends` and `wides`,
    // translated from their cached origin to `origin`, and returns true. Cached strips whose alphas
    // are no longer resident are dropped.
    bool findCachedStrips(const StripCache::Key& key,
                          SkIPoint origin,
                          EndCaps* ends,
                          WideTiles* wides);
    // Caches the strips just generated for `key`, drawn with the integer translation `origin`.
    // `ends` must not have overflow caps.
    void cacheStrips(const StripCache::Key& key,
                     SkIPoint origin,
                     const EndCaps& ends,
                     const WideTiles& wides);

    // ---- Accessors ----

    // The number of valid regular pages.
    size_t numPages() const {
        size_t numPages = 0;
        for (int32_t i = 0; i < SparseStripConfig::kMaxTexturePages; ++i) {
            if (fPages[i].isValid()) {
                numPages++;
            }
        }
        return numPages;
    }
    int32_t activePageRowCount() const {
        return (fActiveSlot < SparseStripConfig::kMaxTexturePages && fPages[fActiveSlot].isValid())
                       ? fPages[fActiveSlot].fRowCount
                       : 0;
    }
    // `index` may be a regular slot or kOverflowSlot.
    sk_sp<TextureProxy> getPageProxy(size_t index) const {
        const TexturePage* page = this->pageForSlot(index);
        return page && page->isValid() ? page->fTexture : nullptr;
    }
    // `index` may be a regular slot or kOverflowSlot. The overflow page only contains committed
    // alphas; see overflowStagingData() for uncommitted ones.
    const uint8_t* getPageData(size_t index) const {
        const TexturePage* page = this->pageForSlot(index);
        return page && page->isValid() ? page->fAlphaBuffer.data() : nullptr;
    }
    int activeSlot() const { return fActiveSlot; }
    bool hasOverflowStaging() const { return !fOverflowStaging.empty(); }
    const uint8_t* overflowStagingData() const { return fOverflowStaging.data(); }
    int parkedOverflowPageCount() const { return fParkedOverflowPages.size(); }
    const StripCache& stripCache() const { return fStripCache; }
#if defined(GPU_TEST_UTILS)
    // The number of draws that reused cached strips.
    int stripCacheHits() const { return fStripCacheHits; }
#endif

private:
    // The struct backing the manager's pages. Note, the struct contains fAlphaBuffer, which holds
    // the cpu-side data for the page (e.g. a single upload).
    struct TexturePage {
        sk_sp<TextureProxy> fTexture;
        int32_t fRowCount = 0;
        int32_t fCapacityBytes = 0;
        int32_t fUsedBytes = 0;
        int32_t fUploadedRows = 0;
        SkTDArray<uint8_t> fAlphaBuffer;
        uint32_t fID = kInvalidPageID;
        skgpu::Token fLastUseToken = skgpu::Token::InvalidToken();

        bool isValid() const { return fTexture != nullptr; }
        void reset() {
            fTexture = nullptr;
            fRowCount = 0;
            fCapacityBytes = 0;
            fUsedBytes = 0;
            fUploadedRows = 0;
            fAlphaBuffer.clear();
            fID = kInvalidPageID;
            fLastUseToken = skgpu::Token::InvalidToken();
        }
    };

    const TexturePage* pageForSlot(size_t slot) const {
        if (slot < SparseStripConfig::kMaxTexturePages) {
            return &fPages[slot];
        }
        return slot == kOverflowSlot ? &fOverflowPage : nullptr;
    }

    uint32_t newPageID();
    skgpu::Token nextFlushToken() const;
    bool initPage(TexturePage* page, int32_t rows, std::string_view label);
    bool createPageInSlot(int32_t slot, int32_t minRequiredBytes = 0);
    int32_t overflowRowsFor(int32_t numBytes) const;
    bool reserveOverflow(int32_t numBytes);
    bool canOverwrite(const TexturePage& page) const;
    void uploadPage(TexturePage* page, DrawContext* dc);
    void markPagesUsed(const EndCaps& ends);

    Recorder* fRecorder;
    TexturePage fPages[SparseStripConfig::kMaxTexturePages];

    // The overflow page, plus replaced overflow pages whose pending rows still need to be uploaded
    // at the next recordUploads(), after which they are dropped.
    TexturePage fOverflowPage;
    skia_private::TArray<TexturePage> fParkedOverflowPages;

    // CPU staging for the current draw's overflow alphas, consumed by commitOverflow(). Only used
    // while on the kOverflowSlot.
    SkTDArray<uint8_t> fOverflowStaging;
    int32_t fOverflowStagingUsedBytes;

    // Overflow bytes committed since the last regular page was created. The next regular page is
    // sized to absorb them, so that sustained overflow grows the regular pages.
    int64_t fOverflowDemandBytes;
    // Bytes of overflow pages allocated to replace one that was still in use, since the overflow
    // page was last overwritten in place. Compared against kOverflowSoftCapBytes.
    int64_t fOverflowReplacementBytes;

    // The number of open DrawScopes.
    int32_t fInFlightDraws;
    uint32_t fNextPageID;

    // The slot of the texture page whose alpha buffer is currently being appended to, or
    // kOverflowSlot once both regular pages are full.
    int32_t fActiveSlot;
    // The slot of the last regular texture page which was appended to
    int32_t fLastGpuSlot;
    int32_t fNextPageRowCount;
    int32_t fNextOverflowRowCount;

    StripCache fStripCache;
#if defined(GPU_TEST_UTILS)
    int32_t fStripCacheHits = 0;
#endif
};

}  // namespace skgpu::graphite

#endif  // skgpu_graphite_AlphaAtlasManager_DEFINED
