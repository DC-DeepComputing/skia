"""Generates modules/skunicode/src/SkUnicode_hardcoded_tables.h from the Unicode Character
Database, so SkUnicodeHardCodedCharProperties answers getScript and isNonSpacingMark the way
ICU does. Use the UCD version of third_party/externals/icu (U_UNICODE_VERSION in uchar.h):

  curl -O https://www.unicode.org/Public/17.0.0/ucd/Scripts.txt
  curl -O https://www.unicode.org/Public/17.0.0/ucd/PropertyValueAliases.txt
  curl -O https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedGeneralCategory.txt
  python3 tools/unicode/generate_skunicode_tables.py 17.0.0 <dir with the three files> \
      > modules/skunicode/src/SkUnicode_hardcoded_tables.h
"""

import os
import sys

MAX_CODE_POINT = 0x10FFFF


def parse_ucd(path):
    """Yields (first, last, value) for every data line of a UCD range file"""
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.split('#')[0].strip()
            if not line:
                continue
            fields = [field.strip() for field in line.split(';')]
            first, _, last = fields[0].partition('..')
            yield int(first, 16), int(last or first, 16), fields[1]


def script_short_names(path):
    """Maps each long Script value name (Latin) to its ISO 15924 code (Latn)"""
    names = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            fields = [field.strip() for field in line.split('#')[0].split(';')]
            if len(fields) >= 3 and fields[0] == 'sc':
                names[fields[2]] = fields[1]
    return names


def script_ranges(ucd_dir):
    """Returns the ISO 15924 tags and the (first, tag index) start of every run of code points
    that share a script, covering 0..MAX_CODE_POINT; unlisted code points are Zzzz"""
    short = script_short_names(os.path.join(ucd_dir, 'PropertyValueAliases.txt'))
    scripts = ['Zzzz'] * (MAX_CODE_POINT + 1)
    for first, last, name in parse_ucd(os.path.join(ucd_dir, 'Scripts.txt')):
        scripts[first:last + 1] = [short[name]] * (last - first + 1)
    tags = sorted(set(scripts))
    # Each range keeps its tag index in 8 bits next to a 24-bit first code point
    assert len(tags) <= 256
    index = {tag: i for i, tag in enumerate(tags)}
    starts = [(c, index[scripts[c]]) for c in range(MAX_CODE_POINT + 1)
              if c == 0 or scripts[c] != scripts[c - 1]]
    return tags, starts


def mark_ranges(ucd_dir):
    """Returns the merged inclusive ranges of General_Category Mn and Me"""
    ranges = []
    path = os.path.join(ucd_dir, 'extracted', 'DerivedGeneralCategory.txt')
    if not os.path.exists(path):
        path = os.path.join(ucd_dir, 'DerivedGeneralCategory.txt')
    for first, last, category in sorted(parse_ucd(path)):
        if category not in ('Mn', 'Me'):
            continue
        if ranges and ranges[-1][1] + 1 == first:
            ranges[-1] = (ranges[-1][0], last)
        else:
            ranges.append((first, last))
    return ranges


def emit(items, per_line):
    """Prints items as comma-separated rows of per_line entries, indented by 8 spaces"""
    for i in range(0, len(items), per_line):
        print('        ' + ' '.join(item + ',' for item in items[i:i + per_line]))


def main():
    """Reads the UCD version and directory from argv and prints SkUnicode_hardcoded_tables.h"""
    version, ucd_dir = sys.argv[1], sys.argv[2]
    tags, starts = script_ranges(ucd_dir)
    marks = mark_ranges(ucd_dir)
    print(f'''/*
 * Copyright 2026 Google LLC
 *
 * Use of this source code is governed by a BSD-style license that can be
 * found in the LICENSE file.
 */
// Generated by tools/unicode/generate_skunicode_tables.py from Unicode {version}; do not edit
#ifndef SkUnicode_hardcoded_tables_DEFINED
#define SkUnicode_hardcoded_tables_DEFINED

#include "include/core/SkFourByteTag.h"
#include "include/core/SkTypes.h"

#include <array>
#include <cstdint>
#include <utility>

namespace SkUnicodeTables {{

// ISO 15924 tags of the Script property values, indexed by ScriptRange::fScript
inline constexpr std::array<SkFourByteTag, {len(tags)}> kScriptTags{{{{''')
    emit([f"SkSetFourByteTag('{t[0]}', '{t[1]}', '{t[2]}', '{t[3]}')" for t in tags], 2)
    print(f'''}}}};

// A run of code points with one script; it ends where the next range starts
struct ScriptRange {{
    uint32_t fFirst : 24;
    uint32_t fScript : 8;
}};

// Sorted runs that cover U+0000..U+10FFFF, unassigned code points included (Zzzz)
inline constexpr std::array<ScriptRange, {len(starts)}> kScriptRanges{{{{''')
    emit([f'{{0x{c:04X}, {i}}}' for c, i in starts], 5)
    print(f'''}}}};

// Sorted, disjoint inclusive ranges of General_Category Mn (Nonspacing_Mark) and Me
// (Enclosing_Mark)
inline constexpr std::array<std::pair<SkUnichar, SkUnichar>, {len(marks)}>
        kNonSpacingMarkRanges{{{{''')
    emit([f'{{0x{a:04X}, 0x{b:04X}}}' for a, b in marks], 4)
    print('''}};

}  // namespace SkUnicodeTables

#endif  // SkUnicode_hardcoded_tables_DEFINED''')


if __name__ == '__main__':
    main()
