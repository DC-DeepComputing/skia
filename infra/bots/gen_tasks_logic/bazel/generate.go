package main

import (
	"context"
	"fmt"
	"os"
	"strings"

	"go.skia.org/infra/go/exec"
)

const (
	targetFile = "targets_gen.go"
	fileTmpl   = `// Code generated by "go run generate.go"; DO NOT EDIT

package bazel

var sanitizedNameToTarget = map[string]string{
%s
}

var shorthandToTarget = map[string]string{
%s
}

var ambiguousShorthands = map[string][]string{
%s
}
`

	entryTmpl = `	"%s": "%s",`
)

func sanitizeTarget(target string) string {
	rv := target
	rv = strings.TrimPrefix(rv, "//")
	rv = strings.ReplaceAll(rv, "/", "_")
	rv = strings.ReplaceAll(rv, ":", "__")
	rv = strings.ReplaceAll(rv, ".", "_")
	return rv
}

func shorthand(target string) string {
	split := strings.Split(target, ":")
	if len(split) != 2 {
		panic("Target " + target + " should have exactly one colon")
	}
	return split[1]
}

func main() {
	// Collect all of the targets.
	// TODO(borenet): We'd actually prefer "bazelisk query //...", but that
	// gives a bunch of errors.
	ctx := context.Background()
	queries := []string{
		"//:*",
		"//bench/...",
		"//example/external_client:*", // This causes an "infinite symlink" error with "/..."
		"//gm/...",
		"//include/...",
		"//modules/...",
		"//src/...",
		"//tests/...",
		"//tools/...",
	}
	targets := []string{}
	for _, query := range queries {
		out, err := exec.RunCwd(ctx, ".", "bazelisk", "query", query)
		if err != nil {
			panic(err)
		}
		for _, target := range strings.Split(strings.TrimSpace(out), "\n") {
			if strings.HasPrefix(target, "//") {
				targets = append(targets, target)
			}
		}
	}

	// Map the sanitized version of every label to actual label.
	sanitizedNameToTargetParts := make([]string, 0, len(targets))
	shorthandToTargetParts := make([]string, 0, len(targets))
	for _, target := range targets {
		sanitized := sanitizeTarget(target)
		sanitizedNameToTargetParts = append(sanitizedNameToTargetParts, fmt.Sprintf(entryTmpl, sanitized, target))
	}

	// Map the shorthand version of every label (just the target name) to all of
	// the full label it could refer to.
	shorthandToTargets := make(map[string][]string, len(targets))
	for _, target := range targets {
		short := shorthand(target)
		shorthandToTargets[short] = append(shorthandToTargets[short], target)
	}

	// Use the target name as the shorthand, but only if the target name is
	// unambiguous across all targets.
	for _, target := range targets {
		short := shorthand(target)
		if len(shorthandToTargets[short]) == 1 || strings.HasPrefix(target, "//:") {
			shorthandToTargetParts = append(shorthandToTargetParts, fmt.Sprintf(entryTmpl, short, target))
		}
	}

	// Write the mapping of shorthand to targets, so that we can provide a
	// helpful error message in cases where a shorthand is ambiguous.
	shorthandIsAmbiguousParts := []string{}
	for shorthand, targets := range shorthandToTargets {
		if len(targets) > 1 {
			parts := make([]string, 0, len(targets))
			for _, target := range targets {
				parts = append(parts, "\""+target+"\"")
			}
			line := fmt.Sprintf(`	"%s": {%s},`, shorthand, strings.Join(parts, ", "))
			shorthandIsAmbiguousParts = append(shorthandIsAmbiguousParts, line)
		}
	}

	// Write the file contents.
	sanitizedNameToTarget := strings.Join(sanitizedNameToTargetParts, "\n")
	shorthandToTarget := strings.Join(shorthandToTargetParts, "\n")
	shorthandIsAmbiguous := strings.Join(shorthandIsAmbiguousParts, "\n")
	contents := fmt.Sprintf(fileTmpl, sanitizedNameToTarget, shorthandToTarget, shorthandIsAmbiguous)
	if err := os.WriteFile("targets_gen.go", []byte(contents), os.ModePerm); err != nil {
		panic(err)
	}
}
